#!/bin/bash
# Campaign-31 SURFACE generator: the Maintenance > Hours page's public contract
# (hour machines/readings/events routes, schemas, tables, settings keys,
# permissions, migration, frontend exports, API client methods, i18n keys).
# Regenerate the whole file with:  bash tools/gen_surface_hours.sh > SURFACE.md
# Every section is produced by the `regen:` command printed above it, so the
# file is byte-replayable. ANY diff = a surface change = the iteration FAILS
# unless the user approved it (BASELINE-CHANGELOG.md entry in the same commit).
# No section pins line numbers (names, routes and order only).
set -u
cd "$(dirname "$0")/.." || exit 1

BE_ROUTES='backend/app/api/routes/printer_hours.py'
BE_SRC="$BE_ROUTES backend/app/services/printer_hours.py"
FE_SRC='frontend/src/components/maintenance/hours frontend/src/utils/hoursSeries.ts'

R1='./venv/bin/python3 -c "from backend.app.main import app; [print(r.path, sorted(r.methods)) for r in sorted(app.routes, key=lambda r: r.path) if hasattr(r, \"methods\") and \"/maintenance/hours\" in r.path]" 2>/dev/null'
R2="grep -hE '^@[a-z_]*router\.(get|post|put|patch|delete)\(' $BE_ROUTES | sed 's/, *\$//' | sort"
R3="grep -hE '^(def|class|async def) [a-zA-Z]' $BE_SRC | sed 's/) *->.*/)/; s/:\$//' | sort"
R4="grep -hoE '^class (Hour|Hours)[A-Za-z0-9_]*' backend/app/schemas/maintenance.py backend/app/models/maintenance.py | sort"
R5='./venv/bin/python3 -c "
import json, inspect
from pydantic import BaseModel
import backend.app.schemas.maintenance as m
out = {}
for n, k in sorted(vars(m).items()):
    if inspect.isclass(k) and issubclass(k, BaseModel) and k.__module__ == m.__name__ and n.startswith((\"Hour\", \"Hours\")):
        out[n] = {f: str(x.annotation) for f, x in sorted(k.model_fields.items())}
print(json.dumps(out, indent=1, sort_keys=True))" 2>/dev/null'
R6='./venv/bin/python3 -c "import backend.app.main; from sqlalchemy.schema import CreateTable, CreateIndex; from sqlalchemy.dialects import sqlite; from backend.app.core.database import Base; [print(str(CreateTable(t).compile(dialect=sqlite.dialect())).strip() + \";\") or [print(str(CreateIndex(i).compile(dialect=sqlite.dialect())).strip() + \";\") for i in sorted(t.indexes, key=lambda i: i.name or \"\")] for n, t in sorted(Base.metadata.tables.items()) if n.startswith(\"hour_\")]" 2>/dev/null'
R7="grep -hoE 'get_setting\(db, \"[a-z_]+\"|set_setting\(db, \"[a-z_]+\"|\"[a-z_]+_key\"|_[A-Z_]+_KEY = \"[a-z_]+\"|READINGS_DUE_KIND = \"[a-z_.]+\"|os\.environ\.get\(\"[A-Z_]+\"|settings\.[a-z_]+' $BE_SRC | sort | uniq -c | sed 's/^ *//'"
R8="grep -hoE 'Permission\.[A-Z_]+' $BE_ROUTES | sort | uniq -c | sed 's/^ *//'"
R9='grep -nE "_migrate_printer_hours_columns|hour_machines|hour_readings|hour_events" backend/app/core/database.py | sed "s/^[0-9]*://; s/^[[:space:]]*//" | sort -u'
R10="grep -rhoE --include='*.ts' --include='*.tsx' '^export (default function|default async function|async function|function|const|type|interface|class|enum) [A-Za-z0-9_]+' $FE_SRC | sort | uniq -c | sed 's/^ *//'"
R11='grep -nE "HoursTab|hours" frontend/src/pages/MaintenancePage.tsx | grep -iE "HoursTab|tab.*hours|hours.*tab" | sed "s/^[0-9]*://; s/^[[:space:]]*//"'
R12='sed -n "/^export interface HourMachine {/,/^\/\/ External Links/p" frontend/src/api/client.ts | grep -vE "^// External Links"'
R13='grep -nE "^  (get|set|save|delete|import|add|update|patch)[A-Za-z]*(Hour|Reading|Machine)[A-Za-z]*: " frontend/src/api/client.ts | sed "s/^[0-9]*://; s/^[[:space:]]*//; s/ *=>.*//"'
R14="grep -rhoE --include='*.ts' --include='*.tsx' \"maintenance\.hours\.[a-zA-Z0-9_]+(\.[a-zA-Z0-9_]+)*\" $FE_SRC | sort -u"
R15="grep -hoE 'useQuery|useMutation|queryKey: \[[^]]*\]|invalidateQueries\([^)]*\)' frontend/src/components/maintenance/hours/*.tsx | sort | uniq -c | sed 's/^ *//'"

emit() { # emit <heading> <cmd>
  local heading="$1" cmd="$2"
  echo "## $heading"
  echo "\`\`\`regen: $cmd\`\`\`"
  echo '```'
  eval "$cmd"
  echo '```'
  echo ''
}

echo '# SURFACE.md — campaign-31 public contract: the Maintenance > Hours page (frozen at setup)'
echo ''
echo 'Generated by `bash tools/gen_surface_hours.sh > SURFACE.md`. Each section is'
echo 'replayable by the `regen:` command shown above it. Any diff against the'
echo 'committed copy is a change to something outside the feature`s own'
echo 'internals — a route, a schema field, a table column, an exported symbol,'
echo 'a setting or permission the feature reads, a translation key, an API'
echo 'client method — and fails the iteration unless the user approved it.'
echo ''

emit 'HTTP routes under /maintenance/hours' "$R1"
emit 'Route decorators (printer_hours.py)' "$R2"
emit 'Backend public callables (routes + service)' "$R3"
emit 'Pydantic schema + ORM model class names (Hour*)' "$R4"
emit 'Pydantic schema fields (schemas/maintenance.py Hour*)' "$R5"
emit 'Tables the feature owns — DDL (hour_*)' "$R6"
emit 'Settings keys, env vars and config attributes read by the backend' "$R7"
emit 'Permissions guarding the routes (count per permission)' "$R8"
emit 'Migration touching the feature (core/database.py)' "$R9"
emit 'Frontend exported symbols (count per symbol name)' "$R10"
emit 'MaintenancePage.tsx — Hours tab wiring' "$R11"
emit 'API client — Hour* exported types' "$R12"
emit 'API client — hours methods' "$R13"
emit 'Translation keys the Hours UI reads (maintenance.hours.* literals)' "$R14"
emit 'React Query keys and invalidations in the Hours components' "$R15"
