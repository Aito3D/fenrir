#!/bin/bash
# Campaign Q1 (print queue) SURFACE generator: the print queue's public contract.
# Regenerate the whole file with:  bash tools/gen_surface_queue.sh > /tmp/surface-q1.md && mv /tmp/surface-q1.md SURFACE.md
# Every section is produced by the `regen:` command printed above it, so the
# file is byte-replayable. ANY diff = a surface change = the iteration FAILS.
# Private helpers (leading underscore) are deliberately NOT pinned. Backend
# sections glob `print_queue*.py` and `print_queue/`, `queue_*.py` and `queue_*/`,
# so a module split out of a scope file shows up here as new lines to review.
set -u
mkdir -p /tmp/fenrir-queue-probe/surface
cd "$(dirname "$0")/.." || exit 1
export LC_ALL=C

BE_SCOPE='$(ls -d backend/app/api/routes/print_queue*.py backend/app/api/routes/print_queue/*.py backend/app/services/queue_*.py backend/app/services/queue_*/*.py backend/app/models/print_queue*.py backend/app/schemas/print_queue*.py 2>/dev/null | sort)'
FE_SCOPE='frontend/src/pages/QueuePage.tsx $(ls frontend/src/components/Queue*.tsx | sort) frontend/src/components/PrinterQueueWidget.tsx $(find frontend/src/components/queue -type f | sort) $(ls frontend/src/utils/queue*.ts | sort)'
PYENV='PYTHONHASHSEED=0 PYTHONDONTWRITEBYTECODE=1 DATA_DIR=/tmp/fenrir-queue-probe/surface LOG_TO_FILE=false ./venv/bin/python3'

R1="$PYENV"' -c "from backend.app.main import app; [print(sorted(r.methods), r.path, r.endpoint.__name__) for r in app.routes if hasattr(r, \"methods\") and r.path.startswith(\"/api/v1/queue/\")]" 2>/dev/null'
R2='grep -hE "^@router\.(get|post|put|delete|patch)\(" $(ls -d backend/app/api/routes/print_queue*.py backend/app/api/routes/print_queue/*.py 2>/dev/null | sort)'
R3='for f in '"$BE_SCOPE"'; do echo "# $f"; grep -E "^(def|class|async def) [a-zA-Z]|^[A-Za-z][A-Za-z_0-9]* = |^[A-Z][A-Z_0-9]*: " "$f" | sed -E "s/ = .*/ =/; s/(def [a-zA-Z_0-9]+)\(.*/\1(/"; done'
R4="$PYENV"' -c "
import inspect
from pydantic import BaseModel
import backend.app.schemas.print_queue as mod
for n, c in sorted(vars(mod).items()):
    if inspect.isclass(c) and issubclass(c, BaseModel) and c.__module__.startswith(mod.__name__):
        print(n + \": \" + \", \".join(f + \": \" + str(x.annotation).replace(\"typing.\", \"\") for f, x in c.model_fields.items()))
" 2>/dev/null | sed -E "s/ at 0x[0-9a-f]+//g"'
R5='grep -hE "__tablename__|^class |^    [a-z_]+: Mapped\[|UniqueConstraint|Index\(" backend/app/models/print_queue.py | sed -E "s/ *= *(mapped_column|relationship).*//"'
R6='grep -E "print_queue|PrintQueue" backend/app/core/database.py | sed -E "s/^ +//"'
R7='grep -hE "QUEUE_" backend/app/core/permissions.py backend/app/core/auth.py | sed -E "s/^ +//"'
R8='grep -E "print_queue\.router|^ +print_queue,$|services\.queue_(announcements|events|item_printer|position|trace_summary)" backend/app/main.py | sed -E "s/^ +//"'
R9='{ echo "# backend: config attributes and WebSocket message types"; grep -hoE "settings\.[a-z_]+|\"type\": \"[a-z_]+\"" '"$BE_SCOPE"' | sort -u; echo "# frontend: settings fields, query keys, storage keys"; grep -hoE "settings\??\.[a-z_]+|queryKey: \[\x27[A-Za-z-]+\x27|(local|session)Storage\.(get|set|remove)Item\([^,)]+" '"$FE_SCOPE"' | sort -u; }'
R10='for f in '"$FE_SCOPE"'; do grep -HoE "^export (default )?(async )?(function|const|type|interface|class|enum) [A-Za-z0-9_]+" "$f"; done'
R11='grep -E "QueuePage|path=\"queue\"|/queue" frontend/src/App.tsx | sed -E "s/^ +//"'
R12='{ grep -oE "^export (interface|type) [A-Za-z0-9_]*(Queue|Batch)[A-Za-z0-9_]*" frontend/src/api/client.ts; awk -v what=methods -f tools/probe_queue_client.awk frontend/src/api/client.ts | grep -oE "^  [A-Za-z0-9_]+" | sed "s/^  /api./"; }'
R13='perl -nle "print \$1 while /[\x27\"\x60]((?:queue|printers|archives|common|nav|settings|pipelines|projects|aito)\.[\w.]*\w)[\x27\"\x60]/g" '"$FE_SCOPE"' | sort -u'
R14='grep -rhoE "data-testid=\"[^\"]+\"|testId=\"[^\"]+\"|data-testid=\{[^}]+\}" '"$FE_SCOPE"' | sort | uniq -c | sed "s/^ *//"'

emit() { # emit <heading> <cmd>
  local heading="$1" cmd="$2"
  echo "## $heading"
  echo "\`\`\`regen: $cmd\`\`\`"
  echo '```'
  eval "$cmd"
  echo '```'
  echo ''
}

echo '# SURFACE.md — campaign-Q1 public contract: the print queue (frozen at setup)'
echo ''
echo 'Generated by `bash tools/gen_surface_queue.sh > /tmp/surface-q1.md && mv /tmp/surface-q1.md SURFACE.md`.'
echo 'Each section is replayable by the `regen:` command shown above it. Any diff'
echo 'against the committed copy is a change to something outside the feature`s own'
echo 'internals — a route, a request/response field, a public function, a table'
echo 'column, a permission, a settings key, an exported component, a client type or'
echo 'method, a translation key the UI reads or a test id — and fails the iteration'
echo 'unless the user approved it.'
echo ''

emit 'HTTP routes under /api/v1/queue (registration order)' "$R1"
emit 'Route decorators (routes/print_queue)' "$R2"
emit 'Public functions, classes and constants per in-scope backend module' "$R3"
emit 'Schema models (schemas/print_queue.py), with fields' "$R4"
emit 'Models — print_queue / print_queue_variants columns and relationships' "$R5"
emit 'core/database.py lines touching print_queue (migrations, model registration)' "$R6"
emit 'Permissions QUEUE_* (permissions.py, auth.py)' "$R7"
emit 'main.py wiring' "$R8"
emit 'Settings keys, WebSocket message names, query keys and storage keys the scope uses' "$R9"
emit 'Frontend exports — QueuePage, Queue*.tsx, PrinterQueueWidget, components/queue, utils/queue*' "$R10"
emit 'App.tsx wiring' "$R11"
emit 'API client — queue and batch types, api.* methods that call a /queue URL' "$R12"
emit 'Translation keys the scope files name literally' "$R13"
emit 'Test ids the scope binds' "$R14"
