#!/bin/bash
# Campaign O3 (Order Board) SURFACE generator: the Order Board's public contract.
# Regenerate the whole file with:  bash tools/gen_surface_orders.sh > /tmp/surface-orders.md && mv /tmp/surface-orders.md SURFACE.md
# Every section is produced by the `regen:` command printed above it, so the
# file is byte-replayable. ANY diff = a surface change = the iteration FAILS.
# Internal module layout (private helpers, which submodule of a package holds
# what) is deliberately NOT pinned: the two service packages show their __all__.
set -u
mkdir -p /tmp/fenrir-orders-probe/surface
cd "$(dirname "$0")/.." || exit 1
export LC_ALL=C

BE_TOP='backend/app/services/order_board.py backend/app/services/order_board_events.py backend/app/services/order_board_payment.py backend/app/services/order_board_prep_sheet.py backend/app/services/order_board_sms.py backend/app/services/order_board_tracking.py'
FE_SCOPE='$(find frontend/src/components/orders -type f | sort) frontend/src/pages/OrderBoardPage.tsx frontend/src/pages/OrderTrackPage.tsx frontend/src/utils/orderTracking.ts'

R1='PYTHONHASHSEED=0 DATA_DIR=/tmp/fenrir-orders-probe/surface LOG_TO_FILE=false ./venv/bin/python3 -c "from backend.app.main import app; [print(sorted(r.methods), r.path, r.endpoint.__name__) for r in app.routes if hasattr(r, \"methods\") and \"/order-board\" in r.path]" 2>/dev/null'
R2='grep -HE "^@router\.(get|post|put|delete|patch)\(" backend/app/api/routes/order_board/*.py'
R3='for f in backend/app/api/routes/order_board/*.py '"$BE_TOP"'; do echo "# $f"; grep -E "^(def|class|async def) [a-zA-Z]|^[A-Z][A-Z_0-9]* = |^[A-Z][A-Z_0-9]*: " "$f" | sed -E "s/ = .*/ =/; s/(def [a-zA-Z_0-9]+)\(.*/\1(/"; done'
R4='for p in order_board_actions order_board_sync; do echo "# backend/app/services/$p/__init__.py __all__"; sed -n "/^__all__ = \[/,/^\]/p" backend/app/services/$p/__init__.py | grep -oE "\"[A-Za-z_0-9]+\"" | tr -d "\"" | sort | tr "\n" " "; echo; done'
R5='PYTHONHASHSEED=0 DATA_DIR=/tmp/fenrir-orders-probe/surface LOG_TO_FILE=false ./venv/bin/python3 -c "
import importlib, inspect
from pydantic import BaseModel
for m in (\"board\", \"fulfilment\", \"payment\", \"tracking\"):
    mod = importlib.import_module(\"backend.app.api.routes.order_board.\" + m)
    for n, c in sorted(vars(mod).items()):
        if inspect.isclass(c) and issubclass(c, BaseModel) and c.__module__ == mod.__name__:
            print(m + \".\" + n + \": \" + \", \".join(f + \": \" + str(x.annotation).replace(\"typing.\", \"\") for f, x in c.model_fields.items()))
" 2>/dev/null'
R6='grep -hE "__tablename__|^class |^    [a-z_]+: Mapped\[|UniqueConstraint|Index\(" backend/app/models/order_board_doc.py backend/app/models/order_board_event.py | sed -E "s/ *= *mapped_column.*//"'
R7='grep -E "order_board" backend/app/core/database.py | sed -E "s/^ +//"'
R8='grep -hE "ORDERS_" backend/app/core/permissions.py backend/app/core/auth.py | sed -E "s/^ +//"'
R9='grep -E "order_board|order-board|OrderBoard" backend/app/main.py | sed -E "s/^ +//"'
R10='grep -rhoE "\"(order_board|orders)_[a-z_]+\"" backend/app/services backend/app/api/routes/order_board | sort -u'
R11='for f in '"$FE_SCOPE"'; do grep -HoE "^export (default )?(async )?(function|const|type|interface|class|enum) [A-Za-z0-9_]+" "$f"; done'
R12='grep -E "OrderBoard|OrderTrack|path=\"orders\"|/t/o/" frontend/src/App.tsx | sed -E "s/^ +//"'
R13='{ grep -oE "^export (interface|type) (Order[A-Z]|FinishedOrder)[A-Za-z0-9_]*" frontend/src/api/client.ts | grep -v OrderProjectLinks; awk -v what=methods -f tools/probe_orders_client.awk frontend/src/api/client.ts | grep -oE "^  [A-Za-z0-9_]+" | sed "s/^  /api./"; }'
R14='perl -nle "print \$1 while /[\x27\"\x60]((?:orders|aito|common|nav|settings)\.[\w.]*\w)[\x27\"\x60]/g" '"$FE_SCOPE"' | sort -u'
R15='grep -rhoE "data-testid=\"[^\"]+\"|testId=\"[^\"]+\"|data-testid=\{[^}]+\}" '"$FE_SCOPE"' | sort | uniq -c | sed "s/^ *//"'

emit() { # emit <heading> <cmd>
  local heading="$1" cmd="$2"
  echo "## $heading"
  echo "\`\`\`regen: $cmd\`\`\`"
  echo '```'
  eval "$cmd"
  echo '```'
  echo ''
}

echo '# SURFACE.md — campaign-O3 public contract: the Order Board (frozen at setup)'
echo ''
echo 'Generated by `bash tools/gen_surface_orders.sh > /tmp/surface-orders.md && mv /tmp/surface-orders.md SURFACE.md`.'
echo 'Each section is replayable by the `regen:` command shown above it. Any diff'
echo 'against the committed copy is a change to something outside the feature`s own'
echo 'internals — a route, a request/response field, a public function, a table'
echo 'column, a permission, a settings key, an exported component, a client type or'
echo 'method, a translation key the UI reads or a test id — and fails the iteration'
echo 'unless the user approved it.'
echo ''

emit 'HTTP routes under /api/v1/order-board (registration order)' "$R1"
emit 'Route decorators per module (routes/order_board/)' "$R2"
emit 'Public functions, classes and constants per module (route modules + top-level services)' "$R3"
emit 'Service packages — exported names (__all__)' "$R4"
emit 'Request/response models declared by the routes, with fields' "$R5"
emit 'Models — order_board_docs / order_board_events columns' "$R6"
emit 'core/database.py lines touching order_board (migrations, model registration)' "$R7"
emit 'Permissions ORDERS_* (permissions.py, auth.py)' "$R8"
emit 'main.py wiring' "$R9"
emit 'Settings keys and WebSocket message names' "$R10"
emit 'Frontend exports — components/orders, OrderBoardPage, OrderTrackPage, utils/orderTracking' "$R11"
emit 'App.tsx wiring' "$R12"
emit 'API client — Order Board types and api.* methods' "$R13"
emit 'Translation keys the scope files name literally' "$R14"
emit 'Test ids the scope binds' "$R15"
